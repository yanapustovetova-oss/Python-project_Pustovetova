#Рассчитать и вывести периметр и площадь прямоугольника. Расчеты оформить в функции.
def rect_perimeter(a, b):
    """Вычисляет периметр прямоугольника."""
    return 2 * (a + b)


def rect_area(a, b):
    """Вычисляет площадь прямоугольника."""
    return a * b


# Ввод с обработкой исключений в начале
try:
    a = float(input("Введите длину прямоугольника: "))
    b = float(input("Введите ширину прямоугольника: "))

    if a <= 0 or b <= 0:
        print("Стороны должны быть больше нуля!")
    else:
        p = rect_perimeter(a, b)
        s = rect_area(a, b)

        print("Периметр прямоугольника:", p)
        print("Площадь прямоугольника:", s)

except ValueError:
    print("Неправильно ввели! Нужно вводить числа.")
