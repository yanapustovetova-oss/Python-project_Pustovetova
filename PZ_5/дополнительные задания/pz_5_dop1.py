#Даны три целых числа. Определить, у какого числа больше сумма цифр. Вывод результата предусмотреть в основной программе.
# Расчет суммы цифр оформить в функции.
def sum_digits(num):
    """Считает сумму цифр числа."""
    num = abs(num)  # на случай, если число отрицательное
    total = 0
    while num > 0:
        total += num % 10
        num = num // 10
    return total


# Ввод с обработкой исключений в начале
try:
    a = int(input("Введите первое число: "))
    b = int(input("Введите второе число: "))
    c = int(input("Введите третье число: "))

    # Расчет сумм цифр
    sum_a = sum_digits(a)
    sum_b = sum_digits(b)
    sum_c = sum_digits(c)

    # Вывод результата в основной программе
    print("Сумма цифр первого числа:", sum_a)
    print("Сумма цифр второго числа:", sum_b)
    print("Сумма цифр третьего числа:", sum_c)

    if sum_a >= sum_b and sum_a >= sum_c:
        print("Больше всего сумма цифр у первого числа.")
    elif sum_b >= sum_a and sum_b >= sum_c:
        print("Больше всего сумма цифр у второго числа.")
    else:
        print("Больше всего сумма цифр у третьего числа.")

except ValueError:
    print("Неправильно ввели! Нужно вводить целые числа.")