#Дан прямоугольник, длины сторон которого равны натуральным числам A и B. Составить функцию, которая будет находить,
# на сколько квадратов можно разрезать данный прямоугольник, если от него каждый раз отрезать квадрат наибольшей площади.
def count_squares(a, b):
    """Считает количество квадратов при разрезании прямоугольника A x B."""
    count = 0
    while a > 0 and b > 0:
        if a > b:
            count += a // b
            a = a % b
        else:
            count += b // a
            b = b % a
    return count


try:
    A = int(input("Введите сторону A: "))
    B = int(input("Введите сторону B: "))
    if A <= 0 or B <= 0:
        print("Стороны должны быть больше нуля!")
    else:
        print("Количество квадратов:", count_squares(A, B))
except ValueError:
    print("Неправильно ввели!")
