# Ввести 2 числа. Если их произведение отрицательно, умножить его на 8, в противном
# случае увеличить его в 1.5 раза.

a, b = float(input("Ввведите первое число: ")), float(input("Введите второе число: "))
if a * b < 0:
    result1 = (a * b) * 8
    print(result1)
elif a * b == 0:
    print("Произведение равно 0. Введите другие числа.")
else:
    result2 = (a * b) * 1.5
    print(result2)
